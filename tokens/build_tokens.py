"""Generate every stack's token file from tokens/tokens.json, so all stacks stay in sync.

    python tokens/build_tokens.py           write the outputs
    python tokens/build_tokens.py --check   write nothing; exit 1 if any output is out of date

Outputs (all marked "generated, do not edit"):
    tokens/tokens.css               CSS custom properties (:root), for apps that want the tokens without the kit
    web/retro.css                   the :root block between the "tokens:begin" and "tokens:end" markers
    tokens/_tokens.scss             SCSS variables and maps
    tokens/tailwind.preset.js       Tailwind CSS v3 preset (colors, fonts, glows, stripes)
    tokens/tailwind.theme.css       Tailwind CSS v4 @theme block and utilities
    dotnet/winforms/RetroPalette.cs System.Drawing colours and font names for WinForms
    dotnet/wpf/RetroColors.xaml     WPF Color, SolidColorBrush, gradient brushes and glow effects

Standard library only. Output is deterministic: running it twice changes nothing.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "tokens" / "tokens.json"
BEGIN = "/* tokens:begin (generated by tokens/build_tokens.py from tokens/tokens.json; edit those, not this block) */"
END = "/* tokens:end */"
HEADER = "Generated by tokens/build_tokens.py from tokens/tokens.json. Do not edit by hand."


# ---------- value helpers ----------

def num(value):
    """1.5 -> '1.5', 2.0 -> '2', -1.5 -> '-1.5'."""
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def parse_color(text):
    """'#rrggbb' or 'rgba(r, g, b, a)' -> (r, g, b, alpha 0..255)."""
    text = text.strip()
    match = re.fullmatch(r"#([0-9a-fA-F]{6})", text)
    if match:
        h = match.group(1)
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255
    match = re.fullmatch(r"rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)", text)
    if match:
        r, g, b = (int(match.group(i)) for i in (1, 2, 3))
        alpha = float(match.group(4))
        if not all(0 <= c <= 255 for c in (r, g, b)) or not 0 <= alpha <= 1:
            raise ValueError(f"colour out of range: {text}")
        return r, g, b, int(alpha * 255 + 0.5)
    raise ValueError(f"unsupported colour (use #rrggbb or rgba(...)): {text}")


def argb_hex(text):
    r, g, b, a = parse_color(text)
    return f"#{a:02X}{r:02X}{g:02X}{b:02X}"


def pascal(name):
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_]", name))


def css_font(spec):
    return ", ".join([f'"{spec["family"]}"'] + spec["fallback"])


class Tokens:
    def __init__(self, data):
        self.data = data
        self.color = data["color"]
        self.stripes = data["stripes"]
        self.semantic = data["semantic"]
        for name in self.stripes + data["trail"]["colors"] + list(self.semantic.values()):
            if name not in self.color:
                raise SystemExit(f"FAIL: tokens.json refers to an unknown colour '{name}'")
        for value in self.color.values():
            parse_color(value)

    # Gradients, given a function that turns a palette name into a CSS colour reference.
    def stripes_hard(self, ref):
        n = len(self.stripes)
        parts = []
        for i, name in enumerate(self.stripes):
            stop = f"{num(round((i + 1) * 100 / n, 2))}%"
            parts.append(f"{ref(name)} 0 {stop}" if i < n - 1 else f"{ref(name)} 0")
        return parts

    def stripes_soft(self, ref):
        return [ref(name) for name in self.stripes]

    def trail(self, ref):
        t = self.data["trail"]
        line, gap = t["line"], t["gap"]
        parts, y = [], 0
        for i, name in enumerate(t["colors"]):
            parts.append(f"{ref(name)} {y}px {y + line}px" if y else f"{ref(name)} 0 {line}px")
            y += line
            if i < len(t["colors"]) - 1:
                parts.append(f"transparent {y}px {y + gap}px")
                y += gap
        return parts

    def trail_height(self):
        t = self.data["trail"]
        return len(t["colors"]) * t["line"] + (len(t["colors"]) - 1) * t["gap"]

    def glow(self, name):
        return ", ".join(f"0 0 {num(blur)}px {color}" for blur, color in self.data["glow"][name])

    def split(self):
        return ", ".join(f"{num(x)}px 0 {color}" for x, color in self.data["split"])


# ---------- CSS ----------

def css_root_lines(t):
    var = lambda name: f"var(--rt-{name})"  # noqa: E731
    c = t.color
    lines = []
    base = [k for k in c if k not in t.stripes and k not in ("cyan", "yellow", "red", "green")]
    lines += [f"  --rt-{k}: {c[k]};" for k in base]
    lines.append("")
    lines.append("  /* The seven speed-stripe colors, violet to lime, as in the TV idents. */")
    lines += [f"  --rt-{k}: {c[k]};" for k in t.stripes]
    lines.append("")
    lines += [f"  --rt-{k}: {c[k]};" for k in c if k in ("cyan", "yellow", "red", "green")]
    lines.append("")
    lines.append("  /* Roles: components use these, so a re-map here re-colours every alert, tag and button state. */")
    lines += [f"  --rt-{role}: {var(name)};" for role, name in t.semantic.items()]
    lines.append("")
    hard = t.stripes_hard(var)
    lines.append("  --rt-stripes: linear-gradient(90deg,")
    lines.append("    " + ", ".join(hard[:4]) + ",")
    lines.append("    " + ", ".join(hard[4:]) + ");")
    lines.append("  --rt-stripes-soft: linear-gradient(90deg,")
    lines.append("    " + ", ".join(t.stripes_soft(var)) + ");")
    lines.append(f"  /* Three-line light trail (the \"broadcast yourself\" streak). {t.trail_height()}px tall. */")
    lines.append("  --rt-trail: linear-gradient(180deg,")
    lines.append("    " + ", ".join(t.trail(var)) + ");")
    lines.append("")
    lines += [f"  --rt-glow-{name}: {t.glow(name)};" for name in t.data["glow"]]
    lines.append(f"  --rt-split: {t.split()};")
    lines.append("")
    lines += [f"  --rt-font-{name}: {css_font(spec)};" for name, spec in t.data["font"].items()]
    lines.append("")
    lines.append(f"  --rt-radius: {t.data['radius']}px;")
    lines.append(f"  --rt-ease-out: {t.data['motion']['ease-out']};")
    return lines


def tokens_css(t):
    return "\n".join([f"/* {HEADER} */", "", ":root {"] + css_root_lines(t) + ["}", ""])


def retro_css(t, current):
    block = "\n".join([BEGIN, ":root {"] + css_root_lines(t) + ["}", END])
    if current.count(BEGIN) != 1 or current.count(END) != 1:
        raise SystemExit("FAIL: web/retro.css must hold exactly one tokens:begin and one tokens:end marker")
    start = current.index(BEGIN)
    stop = current.index(END) + len(END)
    return current[:start] + block + current[stop:]


# ---------- SCSS ----------

def scss(t):
    lit = lambda name: t.color[name]  # noqa: E731
    out = [f"// {HEADER}", "// Usage: @use \"tokens\" as rt;  then  color: rt.$rt-yellow;", ""]
    out += [f"$rt-{k}: {v};" for k, v in t.color.items()]
    out += [f"$rt-{role}: $rt-{name};" for role, name in t.semantic.items()]
    out.append("")
    out.append("$rt-stripe-colors: (" + ", ".join(lit(n) for n in t.stripes) + ");")
    out.append("$rt-stripes: linear-gradient(90deg, " + ", ".join(t.stripes_hard(lit)) + ");")
    out.append("$rt-stripes-soft: linear-gradient(90deg, " + ", ".join(t.stripes_soft(lit)) + ");")
    out.append("$rt-trail: linear-gradient(180deg, " + ", ".join(t.trail(lit)) + ");")
    out += [f"$rt-glow-{name}: {t.glow(name)};" for name in t.data["glow"]]
    out.append(f"$rt-split: {t.split()};")
    out += [f"$rt-font-{name}: {css_font(spec)};" for name, spec in t.data["font"].items()]
    out.append(f"$rt-radius: {t.data['radius']}px;")
    out.append(f"$rt-ease-out: {t.data['motion']['ease-out']};")
    out.append("")
    out.append("$rt-colors: (")
    out += [f"  \"{k}\": {v}," for k, v in t.color.items()]
    out.append(");")
    out.append("")
    return "\n".join(out)


# ---------- Tailwind ----------

def js_str(value):
    return json.dumps(value)


def tailwind_v3(t):
    lit = lambda name: t.color[name]  # noqa: E731
    colors = dict(t.color)
    colors.update({role: t.color[name] for role, name in t.semantic.items()})
    out = [f"/* {HEADER}", "   Tailwind CSS v3 preset: module.exports = { presets: [require(\"./tailwind.preset.js\")], ... }",
           "   Classes: bg-rt-black, text-rt-yellow, font-rt-display, shadow-rt-cyan, bg-rt-stripes, rt-text-glow-yellow. */",
           "module.exports = {", "  theme: {", "    extend: {", "      colors: {", "        rt: {"]
    out += [f"          {js_str(k)}: {js_str(v)}," for k, v in colors.items()]
    out += ["        },", "      },", "      fontFamily: {"]
    for name, spec in t.data["font"].items():
        stack = [f'"{spec["family"]}"'] + spec["fallback"]
        out.append(f"        {js_str('rt-' + name)}: [{', '.join(js_str(s) for s in stack)}],")
    out += ["      },", "      backgroundImage: {",
            f"        \"rt-stripes\": {js_str('linear-gradient(90deg, ' + ', '.join(t.stripes_hard(lit)) + ')')},",
            f"        \"rt-stripes-soft\": {js_str('linear-gradient(90deg, ' + ', '.join(t.stripes_soft(lit)) + ')')},",
            f"        \"rt-trail\": {js_str('linear-gradient(180deg, ' + ', '.join(t.trail(lit)) + ')')},",
            "      },", "      boxShadow: {"]
    out += [f"        {js_str('rt-' + name)}: {js_str(t.glow(name))}," for name in t.data["glow"]]
    out += ["      },",
            f"      borderRadius: {{ rt: {js_str(str(t.data['radius']) + 'px')} }},",
            f"      transitionTimingFunction: {{ \"rt-out\": {js_str(t.data['motion']['ease-out'])} }},",
            "    },", "  },", "  plugins: [", "    function ({ addUtilities }) {", "      addUtilities({"]
    out += [f"        {js_str('.rt-text-glow-' + name)}: {{ textShadow: {js_str(t.glow(name))} }}," for name in t.data["glow"]]
    out += [f"        \".rt-text-split\": {{ textShadow: {js_str(t.split())} }},", "      });", "    },", "  ],", "};", ""]
    return "\n".join(out)


def tailwind_v4(t):
    lit = lambda name: t.color[name]  # noqa: E731
    out = [f"/* {HEADER}",
           "   Tailwind CSS v4:  @import \"tailwindcss\";  @import \"./tailwind.theme.css\";",
           "   Classes: bg-rt-black, text-rt-yellow, font-rt-display, shadow-rt-cyan, text-shadow-rt-yellow, bg-rt-stripes. */",
           "@theme {"]
    out += [f"  --color-rt-{k}: {v};" for k, v in t.color.items()]
    out += [f"  --color-rt-{role}: {t.color[name]};" for role, name in t.semantic.items()]
    out += [f"  --font-rt-{name}: {css_font(spec)};" for name, spec in t.data["font"].items()]
    out += [f"  --shadow-rt-{name}: {t.glow(name)};" for name in t.data["glow"]]
    out += [f"  --text-shadow-rt-{name}: {t.glow(name)};" for name in t.data["glow"]]
    out.append(f"  --radius-rt: {t.data['radius']}px;")
    out.append(f"  --ease-rt-out: {t.data['motion']['ease-out']};")
    out.append("}")
    out.append("")
    out.append("@utility bg-rt-stripes {")
    out.append(f"  background-image: linear-gradient(90deg, {', '.join(t.stripes_hard(lit))});")
    out.append("}")
    out.append("")
    out.append("@utility bg-rt-stripes-soft {")
    out.append(f"  background-image: linear-gradient(90deg, {', '.join(t.stripes_soft(lit))});")
    out.append("}")
    out.append("")
    out.append("@utility bg-rt-trail {")
    out.append(f"  background-image: linear-gradient(180deg, {', '.join(t.trail(lit))});")
    out.append("}")
    out.append("")
    return "\n".join(out)


# ---------- .NET ----------

def winforms(t):
    out = ["// <auto-generated>", f"// {HEADER}", "// </auto-generated>", "using System.Drawing;", "",
           "namespace RetroNeon", "{",
           "    /// <summary>The retro-neon-ui palette, font names and radius for WinForms and System.Drawing.</summary>",
           "    public static class RetroPalette", "    {"]
    for k, v in t.color.items():
        r, g, b, a = parse_color(v)
        out.append(f"        public static readonly Color {pascal(k)} = Color.FromArgb({a}, {r}, {g}, {b});")
    out.append("")
    out.append("        /// <summary>Semantic roles (accent, info, success, warning, danger).</summary>")
    for role, name in t.semantic.items():
        out.append(f"        public static readonly Color {pascal(role)} = {pascal(name)};")
    out.append("")
    out.append("        /// <summary>The seven speed-stripe colours, violet to lime, in order.</summary>")
    out.append("        public static readonly Color[] Stripes = { " + ", ".join(pascal(n) for n in t.stripes) + " };")
    out.append("")
    for name, spec in t.data["font"].items():
        out.append(f"        public const string Font{pascal(name)} = {json.dumps(spec['family'])};")
    out.append("")
    out.append(f"        public const int Radius = {t.data['radius']};")
    out += ["    }", "}", ""]
    return "\n".join(out)


def wpf(t):
    c = t.color
    out = ["<!-- " + HEADER + " -->",
           "<!-- Merged by RetroNeon.xaml. Keys: Rt.Color.*, Rt.Brush.*, Rt.Brush.Stripes, Rt.Brush.StripesSoft,",
           "     Rt.Brush.Trail, Rt.Glow.* (DropShadowEffect), Rt.CornerRadius. -->",
           "<ResourceDictionary xmlns=\"http://schemas.microsoft.com/winfx/2006/xaml/presentation\"",
           "                    xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\">"]
    names = dict(c)
    for role, name in t.semantic.items():
        names[role] = c[name]
    for k, v in names.items():
        out.append(f"    <Color x:Key=\"Rt.Color.{pascal(k)}\">{argb_hex(v)}</Color>")
    out.append("")
    for k, v in names.items():
        out.append(f"    <SolidColorBrush x:Key=\"Rt.Brush.{pascal(k)}\" Color=\"{argb_hex(v)}\" />")
    out.append("")
    n = len(t.stripes)
    out.append("    <!-- The seven speed stripes as hard colour bands, left to right. -->")
    out.append("    <LinearGradientBrush x:Key=\"Rt.Brush.Stripes\" StartPoint=\"0,0\" EndPoint=\"1,0\">")
    for i, name in enumerate(t.stripes):
        for edge in (i, i + 1):
            out.append(f"        <GradientStop Color=\"{argb_hex(c[name])}\" Offset=\"{num(round(edge / n, 4))}\" />")
    out.append("    </LinearGradientBrush>")
    out.append("    <LinearGradientBrush x:Key=\"Rt.Brush.StripesSoft\" StartPoint=\"0,0\" EndPoint=\"1,0\">")
    for i, name in enumerate(t.stripes):
        out.append(f"        <GradientStop Color=\"{argb_hex(c[name])}\" Offset=\"{num(round(i / (n - 1), 4))}\" />")
    out.append("    </LinearGradientBrush>")
    tr = t.data["trail"]
    height = t.trail_height()
    out.append(f"    <!-- Light trail: three lines top to bottom; use it on an element {height} px tall. -->")
    out.append("    <LinearGradientBrush x:Key=\"Rt.Brush.Trail\" StartPoint=\"0,0\" EndPoint=\"0,1\">")
    y = 0
    for i, name in enumerate(tr["colors"]):
        top, bottom = y / height, (y + tr["line"]) / height
        out.append(f"        <GradientStop Color=\"{argb_hex(c[name])}\" Offset=\"{num(round(top, 4))}\" />")
        out.append(f"        <GradientStop Color=\"{argb_hex(c[name])}\" Offset=\"{num(round(bottom, 4))}\" />")
        y += tr["line"]
        if i < len(tr["colors"]) - 1:
            out.append(f"        <GradientStop Color=\"#00000000\" Offset=\"{num(round(y / height, 4))}\" />")
            y += tr["gap"]
            out.append(f"        <GradientStop Color=\"#00000000\" Offset=\"{num(round(y / height, 4))}\" />")
    out.append("    </LinearGradientBrush>")
    out.append("")
    out.append("    <!-- Neon glows. WPF has one shadow per effect, so each uses the middle layer of the CSS glow. -->")
    for name, layers in t.data["glow"].items():
        blur, color = layers[len(layers) // 2]
        r, g, b, a = parse_color(color)
        out.append(f"    <DropShadowEffect x:Key=\"Rt.Glow.{pascal(name)}\" ShadowDepth=\"0\" BlurRadius=\"{num(blur * 1.6)}\""
                   f" Color=\"#FF{r:02X}{g:02X}{b:02X}\" Opacity=\"{num(round(a / 255, 2))}\" />")
    out.append("")
    out.append(f"    <CornerRadius x:Key=\"Rt.CornerRadius\">{t.data['radius']}</CornerRadius>")
    out.append("</ResourceDictionary>")
    out.append("")
    return "\n".join(out)


# ---------- main ----------

def outputs(t):
    retro_path = ROOT / "web" / "retro.css"
    return {
        ROOT / "tokens" / "tokens.css": tokens_css(t),
        retro_path: retro_css(t, retro_path.read_text(encoding="utf-8")),
        ROOT / "tokens" / "_tokens.scss": scss(t),
        ROOT / "tokens" / "tailwind.preset.js": tailwind_v3(t),
        ROOT / "tokens" / "tailwind.theme.css": tailwind_v4(t),
        ROOT / "dotnet" / "winforms" / "RetroPalette.cs": winforms(t),
        ROOT / "dotnet" / "wpf" / "RetroColors.xaml": wpf(t),
    }


def main(argv):
    parser = argparse.ArgumentParser(description="Generate every stack's token file from tokens/tokens.json.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if any output is out of date")
    check = parser.parse_args(argv).check
    t = Tokens(json.loads(TOKENS.read_text(encoding="utf-8")))
    stale = []
    for path, text in outputs(t).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            print(f"up to date  {path.relative_to(ROOT).as_posix()}")
            continue
        stale.append(path)
        if check:
            print(f"OUT OF DATE {path.relative_to(ROOT).as_posix()}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote       {path.relative_to(ROOT).as_posix()}")
    if check and stale:
        print(f"{len(stale)} file(s) out of date: run python tokens/build_tokens.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
